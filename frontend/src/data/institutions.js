export const EXCLUDED_INSTITUTIONS = new Set([
  "macfast",
  "macfast tiruvalla",
  "macfast, tiruvalla",
]);

export function mergeInstitutions(extra = []) {
  const set = new Map();
  [...SEED_INSTITUTIONS, ...extra].forEach((raw) => {
    const name = String(raw || "").trim().replace(/\s+/g, " ");
    if (name.length < 2) return;
    if (EXCLUDED_INSTITUTIONS.has(name.toLowerCase())) return;
    const key = name.toLowerCase();
    if (!set.has(key)) set.set(key, name);
  });
  return [...set.values()].sort((a, b) => a.localeCompare(b, undefined, { sensitivity: "base" }));
}

export function filterInstitutions(list, query, limit = 20) {
  const q = String(query || "").trim().toLowerCase();
  if (!q) return list.slice(0, limit);
  const starts = [];
  const contains = [];
  for (const name of list) {
    const lower = name.toLowerCase();
    if (lower.startsWith(q)) {
      starts.push(name);
    } else if (lower.includes(q)) {
      contains.push(name);
    }
    if (starts.length + contains.length >= limit * 3) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
